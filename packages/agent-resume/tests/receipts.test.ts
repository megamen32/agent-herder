import { spawn } from "node:child_process";
import { mkdirSync, mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterEach, beforeEach, expect, it } from "vitest";
import {
  ReceiptLedger,
  nativeAdmissionVerified,
  receiptFingerprint,
  validateIdempotencyKey,
  type BoundTarget,
  type ResumeReceiptRecord,
} from "../src/resume/receipts.js";

// Focused unit: the durable admission ledger.
// Expected <1s/max 15s per file. No provider, harness or native session.
let dir = "";
let ledgerPath = "";

beforeEach(() => {
  dir = mkdtempSync(join(tmpdir(), "herder-receipts-"));
  ledgerPath = join(dir, "state", "receipts.json");
});

afterEach(() => {
  // The temp dir is per-test; nothing outside it is touched.
  dir = "";
});

const target: BoundTarget = { agent: "opencode", session_id: "ses_abc", cwd: "/home/roomhacker/agents-projects", marker: null, model: null };
const fingerprint = (overrides: Partial<Parameters<typeof receiptFingerprint>[0]> = {}) =>
  receiptFingerprint({ target, prompt: "продолжи", goal: "продолжи", idempotencyKey: "key-1", resultRef: "result://1", ...overrides });

it("produces the fingerprint the previous Agent Resume service produced", () => {
  // Pinned digest generated by the Python implementation for exactly this
  // target, prompt, key and result reference. A change in canonicalization must
  // fail here rather than silently orphan every existing receipt.
  expect(fingerprint()).toBe("2d486c627f4e7afb28d286552450a314fce90effcf62cbb323614202eba83b0a");
  expect(fingerprint({ prompt: "другой" })).not.toBe(fingerprint());
  expect(fingerprint({ resultRef: "result://2" })).not.toBe(fingerprint());
});

it("validates an idempotency key the way the service does", () => {
  expect(validateIdempotencyKey(" key ")).toBe("key");
  expect(validateIdempotencyKey("")).toBe("");
  expect(() => validateIdempotencyKey("", { required: true })).toThrow(/required/);
  expect(() => validateIdempotencyKey("x".repeat(513), { required: true })).toThrow(/512/);
});

it("admits one input once and replays the stored receipt", async () => {
  const ledger = new ReceiptLedger({ path: ledgerPath });
  let executions = 0;
  const execute = async (): Promise<ResumeReceiptRecord> => {
    executions++;
    return { receipt_id: "resume-1", receipt_ref: "resume-1", status: "accepted", reason: "prepared", target, executed: true };
  };

  const first = await ledger.admit({ idempotencyKey: "key-1", fingerprint: fingerprint(), target, resultRef: "result://1", execute });
  const replay = await ledger.admit({ idempotencyKey: "key-1", fingerprint: fingerprint(), target, resultRef: "result://1", execute });

  expect(first.status).toBe("accepted");
  expect(replay.receipt_id).toBe("resume-1");
  expect(executions).toBe(1);
});

it("refuses one key claimed by two different inputs, without executing", async () => {
  const ledger = new ReceiptLedger({ path: ledgerPath });
  let executions = 0;
  const execute = async (): Promise<ResumeReceiptRecord> => {
    executions++;
    return { receipt_id: "resume-1", receipt_ref: "resume-1", status: "accepted", target };
  };
  await ledger.admit({ idempotencyKey: "key-1", fingerprint: fingerprint(), target, execute });
  const conflict = await ledger.admit({ idempotencyKey: "key-1", fingerprint: fingerprint({ prompt: "другая цель" }), target, execute });

  expect(conflict).toMatchObject({ status: "rejected", reason: "idempotency_conflict", existing_receipt_id: "resume-1" });
  expect(executions).toBe(1);
});

it("stores a rejected admission so the answer stays stable after a restart", async () => {
  const ledger = new ReceiptLedger({ path: ledgerPath });
  const failed = await ledger.admit({
    idempotencyKey: "key-1", fingerprint: fingerprint(), target,
    execute: async () => ({ receipt_id: "resume-2", receipt_ref: "resume-2", status: "failed", reason: "launch_failed", target }),
  });
  expect(failed.status).toBe("failed");

  // A fresh process reads the same answer and does not retry the launch.
  const afterRestart = new ReceiptLedger({ path: ledgerPath });
  const replay = await afterRestart.admit({
    idempotencyKey: "key-1", fingerprint: fingerprint(), target,
    execute: async () => { throw new Error("must not execute again"); },
  });
  expect(replay).toMatchObject({ status: "failed", receipt_id: "resume-2" });
  expect(afterRestart.read("key-1")).toMatchObject({ status: "failed", reason: "launch_failed" });
  expect(afterRestart.read("unknown-key")).toBeNull();
});

it("promotes an ambiguous admission only with a matching native proof", async () => {
  const ledger = new ReceiptLedger({ path: ledgerPath });
  const codexTarget: BoundTarget = { agent: "codex", session_id: "01a1-thread", cwd: "/home/roomhacker/ServersAdministartion" };
  const codexFingerprint = receiptFingerprint({ target: codexTarget, prompt: "продолжи", idempotencyKey: "key-codex" });
  await ledger.admit({
    idempotencyKey: "key-codex", fingerprint: codexFingerprint, target: codexTarget,
    execute: async () => ({ receipt_id: "resume-3", receipt_ref: "resume-3", status: "ambiguous", reason: "detached_codex_spawn_unverified", target: codexTarget }),
  });

  const wrongSession = await ledger.promoteAmbiguous("key-codex", { fingerprint: codexFingerprint, target: codexTarget, reason: "detached_codex_spawn_unverified" }, { verified: true, agent: "codex", session_id: "other-thread" });
  expect(wrongSession?.status).toBe("ambiguous");

  const promoted = await ledger.promoteAmbiguous("key-codex", { fingerprint: codexFingerprint, target: codexTarget, reason: "detached_codex_spawn_unverified" }, { verified: true, agent: "codex", session_id: "01a1-thread" });
  expect(promoted).toMatchObject({ status: "accepted", reason: "native_admission_verified" });

  // A settled receipt is never rewritten by a later proof.
  const afterAccepted = await ledger.promoteAmbiguous("key-codex", { fingerprint: codexFingerprint, target: codexTarget, reason: "detached_codex_spawn_unverified" }, { verified: true, agent: "codex", session_id: "01a1-thread" });
  expect(afterAccepted?.reason).toBe("native_admission_verified");
});

it("accepts a native proof only when it names the same agent and session", () => {
  expect(nativeAdmissionVerified({ verified: true, agent: "opencode", session_id: "ses_abc" }, target)).toBe(true);
  expect(nativeAdmissionVerified({ verified: false, agent: "opencode", session_id: "ses_abc" }, target)).toBe(false);
  expect(nativeAdmissionVerified({ verified: true, agent: "codex", session_id: "ses_abc" }, target)).toBe(false);
  expect(nativeAdmissionVerified({ verified: true, agent: "opencode" }, target)).toBe(false);
  expect(nativeAdmissionVerified(undefined, target)).toBe(false);
});

it("lets exactly one of two concurrent admissions through the lock", async () => {
  const ledger = new ReceiptLedger({ path: ledgerPath });
  let executions = 0;
  const execute = async (): Promise<ResumeReceiptRecord> => {
    executions++;
    await new Promise((resolve) => setTimeout(resolve, 25));
    return { receipt_id: `resume-${executions}`, receipt_ref: `resume-${executions}`, status: "accepted", target };
  };
  const [first, second] = await Promise.all([
    ledger.admit({ idempotencyKey: "key-race", fingerprint: fingerprint(), target, execute }),
    ledger.admit({ idempotencyKey: "key-race", fingerprint: fingerprint(), target, execute }),
  ]);
  expect(executions).toBe(1);
  expect(first.receipt_id).toBe(second.receipt_id);
});

it("refuses to guess when the ledger is corrupt", () => {
  mkdirSync(join(dir, "state"), { recursive: true });
  writeFileSync(ledgerPath, "{not json", "utf8");
  const ledger = new ReceiptLedger({ path: ledgerPath });
  expect(() => ledger.read("key-1")).toThrow(/unreadable/);
  expect(readFileSync(ledgerPath, "utf8")).toBe("{not json");
});

it("admits while the Agent Resume service keeps its own lock file", async () => {
  // The service guards this ledger with an advisory flock on the same path and
  // leaves that file behind forever. The core must take the same kernel lock
  // instead of needing a directory there: a `mkdir` protocol could never
  // interoperate, and every admission would fall back to the service, which
  // records no native input binding.
  mkdirSync(join(dir, "state"), { recursive: true });
  writeFileSync(`${ledgerPath}.lock`, "", "utf8");
  const ledger = new ReceiptLedger({ path: ledgerPath });
  const receipt = await ledger.admit({
    idempotencyKey: "key-service-lock",
    fingerprint: fingerprint(),
    target,
    execute: async (): Promise<ResumeReceiptRecord> => ({
      receipt_id: "resume-native",
      receipt_ref: "resume-native",
      status: "accepted",
      reason: "prepared",
      target,
      input_id: "herder-resume-abc",
      native_input_message_id: "msg_native",
    }),
  });
  expect(receipt.status).toBe("accepted");
  expect(receipt.input_id).toBe("herder-resume-abc");
  expect(receipt.native_input_message_id).toBe("msg_native");
  expect(ledger.read("key-service-lock")?.native_input_message_id).toBe("msg_native");
});

it("excludes a second writer that already holds the ledger lock", async () => {
  mkdirSync(join(dir, "state"), { recursive: true });
  const lockPath = `${ledgerPath}.lock`;
  // The service holds the same advisory lock; a second admission must wait
  // for it instead of reading a half-written ledger.
  const holder = spawn("flock", ["-x", lockPath, "-c", "echo ready; cat > /dev/null"], { stdio: ["pipe", "pipe", "pipe"] });
  await new Promise<void>((resolve) => holder.stdout?.once("data", () => resolve()));
  const ledger = new ReceiptLedger({ path: ledgerPath });
  const pending = ledger.admit({
    idempotencyKey: "key-contended",
    fingerprint: fingerprint(),
    target,
    execute: async (): Promise<ResumeReceiptRecord> => ({
      receipt_id: "resume-contended",
      receipt_ref: "resume-contended",
      status: "accepted",
      target,
    }),
  });
  holder.kill("SIGKILL");
  const receipt = await pending;
  expect(receipt.status).toBe("accepted");
});